def parse_args(argv=None):
    p = argparse.ArgumentParser(
        prog="tetris.py", description="Single-file terminal Tetris (no dependencies).")
    p.add_argument("--no-color", action="store_true", help="monochrome rendering")
    p.add_argument("--ascii", action="store_true", help="ASCII glyphs only")
    p.add_argument("--next", type=int, default=3, choices=range(1, 6),
                   metavar="N", help="next-piece previews (1-5, default 3)")
    p.add_argument("--start-level", type=int, default=1, choices=range(1, 21),
                   metavar="N", help="starting level (1-20, default 1)")
    p.add_argument("--no-hold", action="store_true", help="disable the HOLD slot")
    p.add_argument("--no-shadow", action="store_true", help="disable the ghost piece")
    p.add_argument("--seed", type=int, help="seed the randomizer (replayable bags)")
    return p.parse_args(argv)


MIN_Y, MIN_X = 23, 44   # 22 board rows + hint row; the title needs 24
TITLE = "T E T R I S"
# Key hints, longest first; the widest one that fits the width is used.
KEY_HINTS = ("arrows move   up rotate   space drop   c hold   p pause   "
             "r restart   ? help",
             "arrows move  up rotate  space drop  c hold  p pause  r restart",
             "arrows move  up rotate  space drop  p pause  r restart",
             "arrows move  rotate  drop  pause  restart",
             "arrows rotate drop pause restart")


def play(stdscr, opts):
    try:
        curses.curs_set(0)
    except curses.error:
        pass
    stdscr.nodelay(True)
    stdscr.keypad(True)
    try:
        stdscr.meta(True)             # deliver Alt/Ctrl byte sequences
    except (curses.error, AttributeError):
        pass
    theme = Theme(stdscr, color=opts.color, force_ascii=opts.ascii)
    game = Game(opts)
    show_help = False
    frame = 1.0 / 60.0
    last = time.monotonic()

    def drain_input():
        """Pump every pending key; returns 'quit' when the player quits."""
        nonlocal show_help
        ch = stdscr.getch()
        while ch != -1:
            if show_help:
                show_help = False
                if ch in (ord("q"), ord("Q")):
                    return "quit"
            else:
                action = game.handle_key(ch)
                if action == "quit":
                    return "quit"
                if action == "help":
                    show_help = True
            ch = stdscr.getch()
        return None

    while True:
        t0 = time.monotonic()
        if drain_input() == "quit":
            return

        size = stdscr.getmaxyx()
        if size[0] < MIN_Y or size[1] < MIN_X:
            stdscr.erase()
            for i, msg in enumerate(("terminal too small",
                                     "resize to at least %d x %d" % (MIN_X, MIN_Y),
                                     "", "q quits")):
                game.safe(stdscr, max(0, size[0] // 2 - 2 + i),
                          max(0, size[1] // 2 - len(msg) // 2), msg, curses.A_BOLD)
            stdscr.refresh()
            curses.napms(60)
            last = t0                 # frozen: resizing must not drain the piece
            continue

        game.update(min(0.25, t0 - last))
        last = t0
        game.draw(stdscr, theme, size)
        if show_help:
            game.draw_help(stdscr, theme, size)

        spent = time.monotonic() - t0
        if spent < frame:
            curses.napms(int((frame - spent) * 1000) + 1)


def main(argv=None):
    args = parse_args(argv)
    if args.seed is not None:
        random.seed(args.seed)
    opts = types.SimpleNamespace(
        next=args.next, start_level=args.start_level, ascii=args.ascii,
        hold=not args.no_hold, shadow=not args.no_shadow,
        color=not args.no_color)
    try:
        curses.wrapper(play, opts)
    except KeyboardInterrupt:                      # Ctrl-C quits like Q
        pass
    return 0


if __name__ == "__main__":
    sys.exit(main())