def terminal_supports_unicode():
    """True when the terminal's locale can encode box drawing and block glyphs.

    sys.stdout.encoding is no help: Python reports utf-8 even under LANG=C,
    where curses silently drops every non-ASCII byte and pieces draw as blank
    space. The locale environment variables are the honest answer, with the
    C library's codeset as a fallback.
    """
    for var in ("LC_ALL", "LC_CTYPE", "LANG"):
        value = (os.environ.get(var) or "").lower().replace("-", "").replace("_", "")
        if not value:
            continue
        if "utf" in value or "unicode" in value:
            return True
        return False        # C, POSIX, latin1, or a codeset-less locale alias
    try:
        codeset = (locale.nl_langinfo(locale.CODESET) or "").lower()
    except (AttributeError, ValueError):
        codeset = ""
    return "utf" in codeset or "unicode" in codeset


class Theme:
    """Terminal-appropriate glyphs and colour pairs."""

    def __init__(self, stdscr, color=True, force_ascii=False):
        self.unicode = not force_ascii and terminal_supports_unicode()
        self.box = (u"╔═╗", u"║ ║", u"╚═╝") if self.unicode else ("+-+", "| |", "+-+")
        self.block = u"\u2588\u2588" if self.unicode else u"[]"
        self.ghost = u"░░" if self.unicode else u"::"
        self.color = color
        self.pairs = {}
        if self.color:
            try:
                curses.start_color()
                curses.use_default_colors()
            except curses.error:
                self.color = False
            if getattr(curses, "COLORS", 0) < 8:
                self.color = False
        if self.color:
            named = {"cyan": curses.COLOR_CYAN, "blue": curses.COLOR_BLUE,
                     "yellow": curses.COLOR_YELLOW, "green": curses.COLOR_GREEN,
                     "magenta": curses.COLOR_MAGENTA, "red": curses.COLOR_RED}
            # curses colour components run 0..1000, not 0..255
            orange = 208 if curses.COLORS >= 256 else None
            if orange is not None:
                try:
                    curses.init_color(orange, 1000, 500, 0)      # ~#FF8000
                except (curses.error, ValueError):
                    orange = None
            for idx, name in enumerate(COLOURS):
                if name is None:
                    continue
                if name == "orange":
                    fg = orange if orange is not None else curses.COLOR_YELLOW
                else:
                    fg = named[name]
                try:
                    # fg only: the block glyph fills the cell, and a default
                    # background keeps empty cells around a shape transparent
                    curses.init_pair(idx, fg, -1)
                    self.pairs[idx] = curses.color_pair(idx)
                except curses.error:
                    pass
            # 20: HUD text, 21: score/toast highlight
            for extra, (fg, bg) in enumerate(
                ((curses.COLOR_WHITE, -1), (curses.COLOR_CYAN, -1)), start=20
            ):
                try:
                    curses.init_pair(extra, fg, bg)
                except curses.error:
                    pass
                self.pairs[extra] = curses.color_pair(extra)

    # attribute helpers -----------------------------------------------------
    def cell_attr(self, color_idx, ghost=False):
        """Colour pair for a cell; block glyphs carry the shape themselves, so
        monochrome terminals still show a solid piece."""
        if ghost:
            return curses.A_DIM | self.pairs.get(color_idx, 0) if self.color \
                else curses.A_DIM
        return self.pairs.get(color_idx, 0) | curses.A_BOLD if self.color \
            else curses.A_BOLD

    @property
    def title(self):
        return (self.pairs.get(20, 0) | curses.A_BOLD) if self.color else curses.A_BOLD

    @property
    def label(self):
        return (self.pairs.get(20, 0) | curses.A_BOLD) if self.color else curses.A_BOLD

    @property
    def accent(self):
        return (self.pairs.get(21, 0) | curses.A_BOLD) if self.color else curses.A_BOLD

    @property
    def flash(self):
        return curses.A_REVERSE | curses.A_BOLD

    @property
    def dim(self):
        return curses.A_DIM


# ---------------------------------------------------------------------------
# Game
# ---------------------------------------------------------------------------

class Game:
    def __init__(self, opts):
        self.opts = opts
        self.best = 0
        self.reset()

    # -- lifecycle ---------------------------------------------------------
    def reset(self):
        self.board = make_board()
        self.bag = []
        self.queue = []
        for _ in range(max(5, self.opts.next) + 1):
            self.queue.append(self._draw_piece())
        self.hold = None
        self.can_hold = True
        self.piece = None
        self.score = 0
        self.lines = 0
        self.level = self.opts.start_level
        self.start_level = self.opts.start_level
        self.combo = -1
        self.b2b = False
        self.pieces_placed = 0
        self.tetris_count = 0
        self.paused = False
        self.over = False
        self.elapsed = 0.0
        self.fall_timer = 0.0
        self.lock_timer = 0.0
        self.lock_resets = 0
        self.lowest = -99
        self.clear_anim = 0.0
        self.anim_rows = []
        self.toast = None
        self.toast_timer = 0.0
        self.last_rot_kick = 0
        self.last_action = "spawn"
        self.spawn_piece()

    def _draw_piece(self):
        if not self.bag:
            self.bag = list(PIECE_ORDER)
            random.shuffle(self.bag)
        return self.bag.pop()

    def spawn_piece(self, kind=None):
        kind = kind or (self.queue.pop(0) if self.queue else self._draw_piece())
        while len(self.queue) < max(5, self.opts.next) + 1:
            self.queue.append(self._draw_piece())
        piece = Piece(kind, y=HIDDEN - 2)
        self.piece = piece
        self.can_hold = True
        self.last_rot_kick = 0
        self.last_action = "spawn"
        self.fall_timer = 0.0
        self.lock_timer = 0.0
        self.lock_resets = 0
        self.lowest = piece.y
        if collides(self.board, piece):        # block out
            piece2 = Piece(kind, y=HIDDEN - 1)
            if collides(self.board, piece2):
                self.game_over()
                return False
            self.piece = piece2
        return True

    def game_over(self):
        self.over = True
        self.paused = False
        self.best = max(self.best, self.score)

    # -- timing ------------------------------------------------------------
    @property
    def gravity(self):
        return gravity_interval(self.level)

    def update(self, dt):
        if self.paused or self.over:
            return
        self.elapsed += dt
        if self.toast_timer > 0:
            self.toast_timer -= dt
            if self.toast_timer <= 0:
                self.toast = None
        if self.clear_anim > 0:
            self.clear_anim -= dt
            if self.clear_anim <= 0:
                self.clear_anim = 0.0
                clear_rows(self.board, self.anim_rows)
                self.anim_rows = []
                self.spawn_piece()
            return

        if self.piece is None:
            return

        # gravity
        self.fall_timer += dt
        interval = self.gravity
        while self.fall_timer >= interval:
            self.fall_timer -= interval
            if collides(self.board, self.piece, dy=1):
                break
            self.piece.y += 1
            self.last_action = "fall"
            if self.piece.y > self.lowest:
                self.lowest = self.piece.y
                self.lock_resets = 0
                self.lock_timer = 0.0

        # lock delay
        if collides(self.board, self.piece, dy=1):
            self.lock_timer += dt
            if self.lock_timer >= LOCK_DELAY:
                self.lock_piece()
        else:
            self.lock_timer = 0.0

    # -- movement input ----------------------------------------------------
    def note_key(self, direction):
        """One movement key event: a press, or one of the terminal's repeats.

        Exactly one step per event. Holding a key repeats at the rate the user
        configured for their terminal, which is the rate they expect.
        """
        self._step(direction)

    def _step(self, direction):
        if direction == "down":
            self.soft_drop()
        else:
            self.move(-1 if direction == "left" else 1)

    # -- actions -----------------------------------------------------------
    def move(self, dx):
        if self.over or self.paused or self.piece is None or self.clear_anim > 0:
            return False
        if collides(self.board, self.piece, dx=dx):
            return False
        self.piece.x += dx
        self.last_action = "move"
        if not collides(self.board, self.piece, dy=1):
            self.lock_timer = 0.0
        elif self.lock_resets < MAX_LOCK_RESETS:
            self.lock_timer = 0.0
            self.lock_resets += 1
        return True

    def rotate(self, direction):
        """direction: +1 clockwise, -1 counter-clockwise. Uses SRS wall kicks."""
        if self.over or self.paused or self.piece is None or self.clear_anim > 0:
            return False
        piece = self.piece
        if piece.kind == "O":
            return False
        table = KICKS_I if piece.kind == "I" else KICKS_JLSTZ
        src = piece.rot
        dst = (src + direction) % 4
        for i, (kx, ky) in enumerate(table[(src, dst)]):
            dx, dy = kx, -ky
            if not collides(self.board, piece, rot=dst, dx=dx, dy=dy):
                piece.rot = dst
                piece.x += dx
                piece.y += dy
                self.last_rot_kick = i
                self.last_action = "rotate%s" % ("ccw" if direction < 0 else "cw")
                if not collides(self.board, piece, dy=1):
                    self.lock_timer = 0.0
                elif self.lock_resets < MAX_LOCK_RESETS:
                    self.lock_timer = 0.0
                    self.lock_resets += 1
                return True
        return False

    def detect_spin(self):
        """3-corner rule; the 5th kick slot promotes a mini to a full T-spin."""
        front, back = count_tspin_corners(self.board, self.piece)
        if front + back < 3:
            return "none"
        if front == 2 or self.last_rot_kick == 4:
            return "full"
        return "mini" if front == 1 else "none"

    def soft_drop(self):
        if self.over or self.paused or self.piece is None or self.clear_anim > 0:
            return False
        if collides(self.board, self.piece, dy=1):
            self.lock_timer = max(self.lock_timer, LOCK_DELAY * 0.4)
            return False
        self.piece.y += 1
        self.last_action = "fall"
        self.score += SOFT_DROP_SCORE
        self.fall_timer = 0.0
        if self.piece.y > self.lowest:
            self.lowest = self.piece.y
            self.lock_resets = 0
            self.lock_timer = 0.0
        return True

    def hard_drop(self):
        if self.over or self.paused or self.piece is None or self.clear_anim > 0:
            return
        dist = ghost_y(self.board, self.piece) - self.piece.y
        self.piece.y += dist
        self.score += HARD_DROP_SCORE * dist
        self.last_action = "harddrop"
        self.lock_piece()

    def hold_swap(self):
        if self.over or self.paused or self.piece is None or self.clear_anim > 0:
            return
        if not self.opts.hold or not self.can_hold:
            return
        current = self.piece.kind
        if self.hold is None:
            self.hold = current
            self.spawn_piece()
        else:
            self.hold, new_kind = current, self.hold
            self.spawn_piece(new_kind)
        self.can_hold = False

    # -- locking & scoring -------------------------------------------------
    def lock_piece(self):
        piece = self.piece
        # A T-spin only counts when the last thing done to the piece was a rotation.
        if piece.kind == "T" and self.last_action.startswith("rotate"):
            self.spin = self.detect_spin()
        else:
            self.spin = "none"
        lock_piece(self.board, piece)
        self.pieces_placed += 1
        rows = full_rows(self.board)
        n = len(rows)

        # game over when a piece locks entirely above the visible field
        if all(y < HIDDEN for _, y in piece.cells()) and not rows:
            self.game_over()
            return

        self.award(n, self.spin)

        if n:
            if n == 4:
                self.tetris_count += 1
            self.lines += n
            new_level = level_for_lines(self.lines, self.start_level)
            if new_level > self.level:
                self.level = new_level
                self.push_toast("LEVEL %d" % self.level, TOAST_TTL)
            self.anim_rows = rows
            self.clear_anim = CLEAR_ANIM
        else:
            self.combo = -1
            self.spawn_piece()
        self.best = max(self.best, self.score)

    def award(self, n, spin):
        base = 0
        label = []
        difficult = False
        if n:
            self.combo += 1
        if spin in ("mini", "full"):
            base += TSPIN_LINE_SCORES.get((spin, n), 0)
            difficult = n > 0
            label.append("T-SPIN" + (" MINI" if spin == "mini" else ""))
        elif n:
            scored = min(n, 4)          # more than four rows at once is not a thing
            base += LINE_SCORES[scored]
            difficult = scored == 4
            label.append(LINE_NAMES[scored])

        if difficult and n:
            if self.b2b:
                base = int(base * B2B_MULTIPLIER)
                label.insert(0, "B2B")
            self.b2b = True
        elif n:
            self.b2b = False

        if self.combo >= 1:
            base += COMBO_SCORE * self.combo
            label.append("COMBO x%d" % self.combo)

        if n and self.would_be_empty():
            base += PERFECT_CLEAR_SCORE
            label.append("PERFECT CLEAR")

        points = base * self.level
        if points:
            self.score += points
        if label:
            self.push_toast(" ".join(label) + ("  +%d" % points if points else ""), TOAST_TTL)

    def would_be_empty(self):
        """True when clearing the full rows leaves the field completely empty."""
        full = set(full_rows(self.board))
        return not any(any(self.board[y]) for y in range(ROWS) if y not in full)

    def push_toast(self, text, ttl=TOAST_TTL):
        self.toast = text
        self.toast_timer = ttl

    def toggle_pause(self):
        if self.over:
            return
        self.paused = not self.paused
        if not self.paused:
            self.best = max(self.best, self.score)

    # -- input -------------------------------------------------------------
    def handle_key(self, ch):
        if ch in (ord("q"), ord("Q")):
            return "quit"
        if ch in (ord("r"), ord("R")):
            self.reset()
            return None
        if ch in (ord("h"), ord("H"), ord("?")):
            return "help"
        if ch in (ord("p"), ord("P")):
            self.toggle_pause()
            return None
        if self.over:
            return None
        if self.paused:
            if ch in (ord(" "), 10, 13):
                self.toggle_pause()
            return None
        if ch in (curses.KEY_LEFT, ord("a"), ord("A")):
            self.note_key("left")
        elif ch in (curses.KEY_RIGHT, ord("d"), ord("D")):
            self.note_key("right")
        elif ch in (curses.KEY_DOWN, ord("s"), ord("S")):
            self.note_key("down")
        elif ch in (curses.KEY_UP, ord("x"), ord("X"), ord("w"), ord("W")):
            self.rotate(1)
        elif ch in (ord("z"), ord("Z")):
            self.rotate(-1)
        elif ch in HOLD_KEYS:
            self.hold_swap()
        elif ch in (ord(" "), 10, 13):
            self.hard_drop()
        return None

    # -- rendering -----------------------------------------------------
    def draw(self, stdscr, theme, size, flush=True):
        maxy, maxx = size
        stdscr.erase()
        layout = self.layout(maxy, maxx)
        self.draw_title(stdscr, theme, layout)
        self.draw_board(stdscr, theme, layout)
        self.draw_hold(stdscr, theme, layout)
        self.draw_next(stdscr, theme, layout)
        self.draw_stats(stdscr, theme, layout)
        self.draw_keys(stdscr, theme, layout)
        if self.toast and not self.paused and not self.over:
            self.draw_toast(stdscr, theme, layout)
        if self.paused:
            self.overlay(stdscr, theme, size,
                         ("PAUSED", "", "press P to resume", "R restart   Q quit"))
        elif self.over:
            self.overlay(stdscr, theme, size,
                         ("GAME OVER", "", "score  %d" % self.score,
                          "best   %d" % self.best, "", "R restart   Q quit"))
        stdscr.noutrefresh()
        if flush:
            curses.doupdate()

    def layout(self, maxy, maxx):
        """Decide where every panel goes for this frame's terminal size.

        The board frame is VIS_ROWS + 2 rows tall; scoring messages reuse its
        bottom border and the key hint sits just under it. The frame is pushed
        down only when there is room for the hint too, so a 24-row terminal
        still shows one.
        """
        board_w = COLS * 2 + 2                      # including its border
        panel_w = 10                                # preview panel width
        wide = maxx >= panel_w * 2 + board_w + 2 and maxy >= MIN_Y
        if wide:
            # centre the HOLD | board | NEXT group as one block
            group = panel_w * 2 + board_w + 2
            left_x = max(1, (maxx - group) // 2)
            board_x = left_x + panel_w + 1
        else:
            left_x = 1
            board_x = max(1, (maxx - board_w) // 2)
        board_y = max(0, min(2, maxy - (VIS_ROWS + 3)))
        title_x = max(0, (maxx - len(TITLE)) // 2)
        show_title = board_y >= 1 or title_x + len(TITLE) < board_x \
            or title_x > board_x + board_w
        return {
            "wide": wide,
            "panel_w": panel_w,
            "board_x": board_x,
            "board_y": board_y,
            # the toast borrows the board's bottom border row: it can never
            # cover a cell, and it exists at every terminal size
            "msg_y": board_y + VIS_ROWS + 1,
            "hint_y": board_y + VIS_ROWS + 2,
            "show_title": show_title,
            "left_x": left_x,
            "right_x": board_x + board_w + 1,
            "maxy": maxy,
            "maxx": maxx,
        }

    def safe(self, stdscr, y, x, text, attr=0):
        """addstr that never throws: clips to the screen, tolerates tiny terms."""
        if not text:
            return
        maxy, maxx = stdscr.getmaxyx()
        if y < 0 or y >= maxy or x >= maxx:
            return
        line = text[: maxx - x]
        if not line:
            return
        try:
            stdscr.addstr(y, x, line, attr)
        except curses.error:
            pass

    def box(self, stdscr, theme, x, y, w, h, title=None):
        if w < 2 or h < 2 or x < 0 or y < 0:
            return
        tl, hz, tr = theme.box[0]
        vl, _, vr = theme.box[1]
        bl, _, br = theme.box[2]
        self.safe(stdscr, y, x, tl + hz * (w - 2) + tr, theme.dim)
        for row in range(y + 1, y + h - 1):
            self.safe(stdscr, row, x, vl, theme.dim)
            self.safe(stdscr, row, x + w - 1, vr, theme.dim)
        self.safe(stdscr, y + h - 1, x, bl + hz * (w - 2) + br, theme.dim)
        if title:
            self.safe(stdscr, y, x + 2, " %s " % title, theme.label)

    def draw_toast(self, stdscr, theme, layout):
        """Score messages ride along the board's bottom border."""
        x, y = layout["board_x"], layout["msg_y"]
        width = COLS * 2 + 2
        text = self.toast
        if len(text) > width - 2:                 # squeeze long messages
            text = text.replace("  ", " ").replace(" + ", " +")
        start = x + max(1, (width - len(text)) // 2)
        self.safe(stdscr, y, start, text[: width - 2], theme.accent)

    def draw_title(self, stdscr, theme, layout):
        if not layout["show_title"]:
            return
        self.safe(stdscr, 0, max(0, (layout["maxx"] - len(TITLE)) // 2), TITLE,
                  theme.title)

    def draw_board(self, stdscr, theme, layout):
        bx, by = layout["board_x"] + 1, layout["board_y"] + 1
        self.box(stdscr, theme, layout["board_x"], layout["board_y"],
                 COLS * 2 + 2, VIS_ROWS + 2)
        show_piece = self.piece is not None and not self.over and self.clear_anim <= 0
        if show_piece and self.opts.shadow:
            gy = ghost_y(self.board, self.piece)
            col = PIECE_COLOR[self.piece.kind]
            for x, y in self.piece.cells(dy=gy - self.piece.y):
                if y >= HIDDEN:
                    self.safe(stdscr, by + y - HIDDEN, bx + x * 2, theme.ghost,
                              curses.A_DIM)
        for y in range(HIDDEN, ROWS):
            row = self.board[y]
            for x in range(COLS):
                v = row[x]
                if v:
                    attr = theme.flash if y in self.anim_rows else theme.cell_attr(v)
                    self.safe(stdscr, by + y - HIDDEN, bx + x * 2, theme.block, attr)
        if show_piece:
            attr = theme.cell_attr(PIECE_COLOR[self.piece.kind])
            for x, y in self.piece.cells():
                if y >= HIDDEN:
                    self.safe(stdscr, by + y - HIDDEN, bx + x * 2, theme.block, attr)

    def draw_mini(self, stdscr, theme, x, y, w, h, kind, dim=False):
        """Centre a piece inside the box whose interior starts at (x, y).

        Only the filled cells are written, so the shape's outline is what the
        player sees; painting the whole bounding box would show a solid block.
        """
        if not kind:
            return
        rows = [r for r in SHAPES[kind][0] if any(r)]
        pw = max(len(r) for r in rows) * 2
        attr = theme.cell_attr(PIECE_COLOR[kind])
        if dim:
            attr |= curses.A_DIM
        ox = x + max(0, (w - pw) // 2)
        oy = y + max(0, (h - len(rows)) // 2)
        for r, row in enumerate(rows):
            for col, cell in self.runs(row):
                self.safe(stdscr, oy + r, ox + col * 2,
                          theme.block * len(cell), attr)

    @staticmethod
    def runs(row):
        """Yield (start_column, cells) for each run of filled cells in a row."""
        start = None
        for i, v in enumerate(list(row) + [0]):
            if v and start is None:
                start = i
            elif not v and start is not None:
                yield start, row[start:i]
                start = None

    def draw_hold(self, stdscr, theme, layout):
        if not self.opts.hold or not layout["wide"]:
            return
        x, y = layout["left_x"], layout["board_y"]
        self.box(stdscr, theme, x, y, layout["panel_w"], 6, "HOLD")
        self.draw_mini(stdscr, theme, x + 1, y + 1, layout["panel_w"] - 2, 4,
                       self.hold, dim=not self.can_hold)

    def draw_next(self, stdscr, theme, layout):
        count = self.opts.next
        h = 2 + count * 3
        if layout["wide"]:
            x, y = layout["right_x"], layout["board_y"]
        else:
            x, y = layout["board_x"] + COLS * 2 + 3, layout["board_y"]
        if x + layout["panel_w"] > layout["maxx"] or y + h > layout["maxy"]:
            return
        self.box(stdscr, theme, x, y, layout["panel_w"], h, "NEXT")
        for i in range(count):
            kind = self.queue[i] if i < len(self.queue) else None
            self.draw_mini(stdscr, theme, x + 1, y + 1 + i * 3,
                           layout["panel_w"] - 2, 3, kind)

    def draw_stats(self, stdscr, theme, layout):
        rows = [("SCORE", "%d" % self.score), ("LINES", "%d" % self.lines),
                ("LEVEL", "%d" % self.level), ("BEST", "%d" % self.best)]
        mins, secs = divmod(int(self.elapsed), 60)
        rows.append(("TIME", "%d:%02d" % (mins, secs)))
        if layout["wide"]:
            x, y = layout["left_x"], layout["board_y"] + 7
        else:
            x = layout["board_x"] + COLS * 2 + 3
            y = layout["board_y"] + 2 + self.opts.next * 3 + 1
        if x + 6 >= layout["maxx"]:
            return
        for i, (label, value) in enumerate(rows):
            if y + i >= layout["maxy"]:
                break
            self.safe(stdscr, y + i, x, "%-5s" % label, theme.label)
            self.safe(stdscr, y + i, x + 6, value,
                      theme.accent if label == "SCORE" else 0)

    def draw_keys(self, stdscr, theme, layout):
        """Key hints along the bottom: squeezed to the widest form that fits."""
        y = layout["hint_y"]
        if y >= layout["maxy"]:
            return
        room = layout["maxx"] - 2
        for hint in KEY_HINTS:
            if len(hint) <= room:
                self.safe(stdscr, y, 1, hint, theme.dim)
                return

    def panel(self, stdscr, theme, size, lines, pad=2):
        """Draw a reverse-video centred box; returns nothing, purely cosmetic."""
        maxy, maxx = size
        w = min(max(len(l) for l in lines) + pad * 2, maxx)
        h = min(len(lines) + 2, maxy)
        y = max(0, (maxy - h) // 2)
        x = max(0, (maxx - w) // 2)
        blank = " " * w
        for row in range(y, y + h):
            self.safe(stdscr, row, x, blank, curses.A_REVERSE)
        tl, hz, tr = theme.box[0]
        vl, _, vr = theme.box[1]
        bl, _, br = theme.box[2]
        self.safe(stdscr, y, x, tl + hz * (w - 2) + tr, curses.A_REVERSE)
        self.safe(stdscr, y + h - 1, x, bl + hz * (w - 2) + br, curses.A_REVERSE)
        for row in range(y + 1, y + h - 1):
            self.safe(stdscr, row, x, vl, curses.A_REVERSE)
            self.safe(stdscr, row, x + w - 1, vr, curses.A_REVERSE)
        for i, line in enumerate(lines[: h - 2]):
            attr = curses.A_REVERSE | (curses.A_BOLD if i == 0 else 0)
            room = max(0, w - pad * 2)
            text = line[:room]
            self.safe(stdscr, y + 1 + i, x + (w - len(text)) // 2, text, attr)

    def overlay(self, stdscr, theme, size, lines):
        self.panel(stdscr, theme, size, lines)

    def draw_help(self, stdscr, theme, size, flush=True):
        lines = (
            "TETRIS - CONTROLS",
            "",
            "left / right  or  A / D    move the piece",
            "down or S                  soft drop  (+1 / cell)",
            "space or enter             hard drop  (+2 / cell)",
            "up / X / W                 rotate clockwise",
            "Z                          rotate counter-clockwise",
            "C or Tab                   hold / swap piece (once per drop)",
            "P                          pause and resume",
            "R                          restart the game",
            "Q                          quit",
            "",
            "1, 2, 3 lines score 100 / 300 / 500, a TETRIS scores 800 and a",
            "T-spin up to 1600. Back-to-back difficult clears score x1.5,",
            "each extra line in a combo adds 50, clearing the whole field",
            "adds 2000. Everything is multiplied by the current level.",
            "",
            "Level up every 10 lines: level %d drops %.2fs per row." % (
                self.level, self.gravity),
            "",
            "press any key to play",
        )
        self.panel(stdscr, theme, size, lines, pad=3)
        stdscr.noutrefresh()
        if flush:
            curses.doupdate()


